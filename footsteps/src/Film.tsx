import React from "react";
import { AbsoluteFill, Audio, Series, staticFile } from "remotion";
import { Act1, ACT1_LEN } from "./scenes/Act1";
import { Act2, ACT2_LEN } from "./scenes/Act2";

export const PARTS: [string, React.FC, number][] = [
  ["Act1", Act1, ACT1_LEN],
  ["Act2", Act2, ACT2_LEN],
];
export const FILM_LEN = PARTS.reduce((a, p) => a + p[2], 0);

export const Film: React.FC = () => (
  <AbsoluteFill style={{ background: "#070504" }}>
    <Series>
      {PARTS.map(([id, C, d]) => (
        <Series.Sequence key={id} durationInFrames={d} name={id}>
          <C />
        </Series.Sequence>
      ))}
    </Series>
    {/* procedural sound design — generated by scripts/sound.py */}
    <Audio src={staticFile("sound.wav")} />
  </AbsoluteFill>
);
